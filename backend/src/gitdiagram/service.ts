import { GoogleGenAI } from '@google/genai';
import { TTLCache } from '../gitingest/cache';
import { GitIngestResult, GitIngestService } from '../gitingest/service';

export interface DiagramResult {
  diagram_id: string;
  repository_url: string;
  mermaid_diagram: string;
  diagram_type: 'component' | 'flowchart' | 'sequence';
  explanation: string;
  generated_at: string;
  method: 'gemini_self_generated' | 'gitdiagram_api';
}

const GITDIAGRAM_API = process.env.GITDIAGRAM_API_URL || 'https://gitdiagram.com';
const CACHE_TTL_MS = Number(process.env.GITINGEST_CACHE_TTL_MS) || 3_600_000;
const cache = new TTLCache<DiagramResult>(CACHE_TTL_MS);
setInterval(() => cache.prune(), 10 * 60 * 1000).unref();

const DIAGRAM_PROMPT = `You are a software architecture expert.
Given the file tree of a software repository, generate a Mermaid component diagram.

Rules:
- Use "graph TD" or "graph LR" syntax
- Group files into logical components (e.g., API, Frontend, Database, Auth)
- Show data/control flow between major components with arrows
- Keep it concise — maximum 30 nodes
- Use descriptive node labels (not file names)
- Return ONLY valid JSON in this exact schema, no extra text:

{
  "mermaid_diagram": "graph TD\\n  A[API Layer] --> B[...]\\n  ...",
  "diagram_type": "component",
  "explanation": "Brief plain-English description of the architecture"
}

File tree:
`;

export class GitDiagramService {
  /**
   * Try the public gitdiagram.com API first; fall back to Gemini self-generation.
   */
  static async generate(repositoryUrl: string): Promise<DiagramResult> {
    const cacheKey = cache.key(`diagram-${repositoryUrl}`);
    const cached = cache.get(cacheKey);
    if (cached) return cached;

    // --- Option A: gitdiagram.com public API ---
    try {
      const result = await GitDiagramService.generateFromApi(repositoryUrl);
      cache.set(cacheKey, result);
      return result;
    } catch (err) {
      console.warn(`[GitDiagram] API call failed, falling back to Gemini self-generation:`, err);
    }

    // --- Option B: self-generate via Gemini using gitingest file tree ---
    const ingest = await GitIngestService.ingest(repositoryUrl);
    const result = await GitDiagramService.generateFromDigest(ingest);
    cache.set(cacheKey, result);
    return result;
  }

  static async generateFromApi(repositoryUrl: string): Promise<DiagramResult> {
    const { owner, repo } = GitIngestService.parseOwnerRepo(repositoryUrl);
    const apiUrl = `${GITDIAGRAM_API}/api/diagram`;

    const response = await fetch(apiUrl, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'User-Agent': 'Valgent-Backend/1.0' },
      body: JSON.stringify({ owner, repo }),
      signal: AbortSignal.timeout(20_000),
    });

    if (!response.ok) {
      throw new Error(`gitdiagram.com API returned ${response.status}`);
    }

    const data = await response.json() as any;
    const mermaid: string = data?.diagram ?? data?.mermaid_diagram ?? '';
    if (!mermaid || mermaid.trim().length < 20) {
      throw new Error('gitdiagram.com returned empty diagram');
    }

    return {
      diagram_id:      `DIAG-${cache.key(repositoryUrl)}`,
      repository_url:  repositoryUrl,
      mermaid_diagram: mermaid,
      diagram_type:    'component',
      explanation:     data?.explanation ?? 'Architecture diagram generated by gitdiagram.com',
      generated_at:    new Date().toISOString(),
      method:          'gitdiagram_api',
    };
  }

  static async generateFromDigest(ingest: GitIngestResult): Promise<DiagramResult> {
    const apiKey = process.env.GEMINI_API_KEY || process.env.gemeni_api || process.env.GEMINI_API;
    if (!apiKey) {
      throw new Error('GEMINI_API_KEY not set — cannot self-generate diagram');
    }

    const ai = new GoogleGenAI({ apiKey });
    const tree = ingest.file_tree.slice(0, 4000) || ingest.digest_text.slice(0, 4000);

    const response = await ai.models.generateContent({
      model: process.env.GEMINI_MODEL || 'gemini-3.5-flash',
      contents: DIAGRAM_PROMPT + tree,
      config: { responseMimeType: 'application/json' }
    });

    if (!response.text) throw new Error('Gemini returned empty diagram response');

    const parsed = JSON.parse(response.text) as {
      mermaid_diagram: string;
      diagram_type: string;
      explanation: string;
    };

    return {
      diagram_id:      `DIAG-${cache.key(ingest.repository_url)}`,
      repository_url:  ingest.repository_url,
      mermaid_diagram: parsed.mermaid_diagram,
      diagram_type:    (parsed.diagram_type as DiagramResult['diagram_type']) ?? 'component',
      explanation:     parsed.explanation,
      generated_at:    new Date().toISOString(),
      method:          'gemini_self_generated',
    };
  }

  static getById(diagramId: string): DiagramResult | null {
    for (const key of Object.keys((cache as any).store ?? {})) {
      const entry = cache.get(key);
      if (entry && entry.diagram_id === diagramId) return entry;
    }
    return null;
  }
}
